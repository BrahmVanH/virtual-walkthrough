import { browser } from '$app/environment';
import { asset } from '$app/paths';

export interface PairReport {
	from: number;
	to: number;
	matches: number;
	/** Matches a pure camera rotation explains. Accepted at 20 or more and at least half of `homographyInliers`. */
	inliers: number;
	/** Matches the best homography explains, for comparison. `null` below 20. */
	homographyInliers: number | null;
	/** Row-major 3x3 homography (full-resolution pixels, `from` to `to`). Diagnostic only. */
	homography: number[] | null;
	/** Row-major 3x3 rotation from camera `from`'s rays into camera `to`'s. `null` when rejected. */
	rotation: number[] | null;
	/** Degrees camera `to` is turned right of camera `from`, under the assumed focal length. */
	yawDegrees: number | null;
	/** A homography explains far more matches than a rotation: the lens moved, or the focal is off. */
	cameraMoved: boolean;
}

/** `outsideGroup`: not in the longest run of joined images. `alongAxis`: camera points straight up or down. */
export type Unplaced = 'outsideGroup' | 'alongAxis';

export type Point = [x: number, y: number];

export interface ImagePlacement {
	index: number;
	width: number;
	height: number;
	/** Focal length assumed for this image, in its own pixels. */
	focal: number;
	/** Row-major 3x3 rotation from this camera's rays into the reference image's. `null` outside the placed group. */
	rotation: number[] | null;
	/**
	 * Image border, clockwise from top-left, in output canvas pixels (centres at integers,
	 * +x = turning right, +y down). `null` when unplaced.
	 */
	outline: Point[] | null;
	/** Set exactly when `outline` is `null`. */
	unplaced: Unplaced | null;
}

/** Output canvas over the unrolled cylinder. Its outer pixel edges sit at -0.5 and `size - 0.5`. */
export interface Canvas {
	width: number;
	height: number;
	/** Bounding box top-left in cylinder pixels (radius × yaw, radius × height). */
	minX: number;
	minY: number;
	/** Canvas pixels per cylinder pixel, at most 1. */
	scale: number;
}

export interface RowAlignment {
	/** Index of the image the cylinder is centred on: the first of the longest run of joined images. */
	reference: number;
	/** Cylinder radius in cylinder pixels (the reference image's focal). One canvas pixel spans 1 / (canvas.scale × radius) radians. */
	radius: number;
	/** `null` only when nothing was placed. */
	canvas: Canvas | null;
	images: ImagePlacement[];
	pairs: PairReport[];
}

export interface PanoStitcher {
	hello(name: string): string;
	/**
	 * Aligns and renders encoded PNG/JPEG bytes in capture order. Omitted or `null` options
	 * use defaults. Blocks the calling thread; throws on decode failure or an out-of-range option.
	 */
	stitch_row(images: Uint8Array[], options?: AlignOptions | null): StitchResult;
}

export interface Panorama {
	width: number;
	height: number;
	/** Row-major RGBA8, ready for `new ImageData(pixels, width, height)`. Uncovered pixels have alpha 0. */
	pixels: Uint8ClampedArray<ArrayBuffer>;
}

export interface StitchResult {
	alignment: RowAlignment;
	/** `null` when no image was placed. */
	panorama: Panorama | null;
}

export interface AlignOptions {
	/** Focal length as a fraction of each image's long side. Default 0.75; ~0.4 for a 0.6× ultra-wide. */
	focalPerLongSide?: number | null;
	/** Lowe ratio in (0, 1], applied in both directions. Default 0.8; lower is stricter. */
	ratio?: number | null;
	/** Strongest keypoints kept per image, at least 20. Default 3000; matching cost grows with its square. */
	maxFeatures?: number | null;
	/** Long-side cap (px, at least 160) for the grayscale copy features come from. Default 1280. */
	featureMaxDim?: number | null;
	/** Long-side cap (px, at least 64) for the output canvas. Default 4096. */
	outputMaxDim?: number | null;
	/**
	 * Unroll each feature image onto a cylinder at `focalPerLongSide` before matching, so
	 * pure yaw between shots becomes a shift. Default true; depends on the focal being close.
	 */
	cylindricalMatching?: boolean | null;
}

let modulePromise: Promise<PanoStitcher> | null = null;

async function init(): Promise<PanoStitcher> {
	// Runtime URL rather than a static import: the package lives in static/wasm/ and is
	// generated by `npm run wasm`, so Vite must not try to resolve or bundle it.
	const url = asset('/wasm/pano_stitcher.js');
	const pkg = await import(/* @vite-ignore */ url);
	await pkg.default();
	return pkg as PanoStitcher;
}

/**
 * Loads and initializes the pano-stitcher WASM package once per page.
 * Browser-only: rejects during SSR. A failed load is not cached, so callers can retry.
 */
export function loadWasmModule(): Promise<PanoStitcher> {
	if (!browser) return Promise.reject(new Error('pano-stitcher WASM is browser-only'));
	modulePromise ??= init().catch((error: unknown) => {
		modulePromise = null;
		throw error;
	});
	return modulePromise;
}
